/** Splits the page text into its introduction and its "## " sections. */
export function thaiSections(md: string) {
  const parts = md.replace(/\r\n?/g, '\n').split(/^##[ \t]+/m);
  const intro = parts.shift()!.trim();
  const sections = parts
    .map((p) => {
      const nl = p.indexOf('\n');
      const title = (nl < 0 ? p : p.slice(0, nl)).trim();
      const body = nl < 0 ? '' : p.slice(nl + 1).trim();
      return { title, body };
    })
    .filter((s) => s.title || s.body);
  return { intro, sections };
}
